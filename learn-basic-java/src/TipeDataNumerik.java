public class TipeDataNumerik {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        System.out.println(a + b);
        System.out.println(b % a);

        // augmented assigment
        int c = 10;
        c += 10;

        System.out.println(c);

        // unary operator
        int d = 10;
        d++;

        System.out.println(d);

        int e = 10;
        ++e;

        System.out.println(e);
    }
}
